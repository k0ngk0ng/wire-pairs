// Classic script transport lets our immutable CDN audio bank load without changing
// the shared CDN's CORS rules. Only the five existing short effects are included.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const files = ['sel.wav', 'elec.wav', 'start.wav', 'end.wav', 'itemboom.wav'];
const bank = Object.fromEntries(files.map(file => [file, readFileSync(new URL(`../public/assets/audio/${file}`, import.meta.url)).toString('base64')]));
const content = `globalThis.__wirePairsEffects = ${JSON.stringify(bank)};\n`;
const hash = createHash('sha256').update(content).digest('hex').slice(0, 12);
writeFileSync(new URL(`../public/assets/audio/effects-${hash}.js`, import.meta.url), content);
writeFileSync(new URL('../src/effectBankPath.ts', import.meta.url), `// Generated by scripts/build-audio-bank.mjs\nexport const effectBankPath = 'audio/effects-${hash}.js';\n`);
console.log(`Built audio/effects-${hash}.js (${Buffer.byteLength(content)} bytes)`);
